def describe(preset: str, auto_source: str, language: str) -> str:
    """What the window in use is for, in `language`."""
    if preset in PRESETS:
        return PRESET_DESCRIPTIONS.get(language, PRESET_DESCRIPTIONS["en"]).get(preset, "")
    notes = WINDOW_NOTES.get(language, WINDOW_NOTES["en"])
    return notes[auto_source if preset == AUTO else "manual"]
